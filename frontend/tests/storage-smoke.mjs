import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({baseURL:'http://127.0.0.1:8000',viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('response',response=>{if(response.status()>=500)errors.push(`${response.status()} ${response.url()}`)});
try {
  await page.goto('http://127.0.0.1:8000',{waitUntil:'domcontentloaded'});
  await page.locator('.photo-card').first().waitFor();
  await page.getByRole('button',{name:'同步目录',exact:true}).waitFor();
  await page.locator('.job-panel').waitFor();
  const settings=await (await page.request.get('/api/settings')).json();
  if(settings.data_dir!=='G:\\修后图'||settings.exports_dir!=='C:\\Users\\wonder\\Downloads')throw new Error('Wrong configured paths');
  const before=await (await page.request.get('/api/photos?page_size=1')).json();
  const beforeCount=Number((await page.locator('.gallery-heading h1 span').textContent()).replaceAll(',',''));
  await page.waitForTimeout(4000);
  const liveCount=Number((await page.locator('.gallery-heading h1 span').textContent()).replaceAll(',',''));
  if(liveCount<beforeCount)throw new Error('Gallery count regressed');
  await fs.mkdir('verification',{recursive:true});
  await page.screenshot({path:'verification/storage-import-progress.png',fullPage:true});
  await page.locator('.photo-image').first().click();
  await page.getByRole('button',{name:'制作水印',exact:true}).click();
  await page.locator('.render-stage img').waitFor();
  await page.getByLabel('文件名模板',{exact:true}).fill('目录验证_20260930');
  await page.waitForFunction(()=>!document.querySelector('.render-status')?.textContent.includes('正在'));
  const exportedResponse=page.waitForResponse(r=>r.url().endsWith('/api/watermark/export')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'导出当前照片',exact:true}).click();
  const response=await exportedResponse;
  if(!response.ok())throw new Error(await response.text());
  const exported=await response.json();
  if(path.dirname(exported.path)!==settings.exports_dir)throw new Error('Wrong export destination');
  if(!(await fs.stat(exported.path)).size)throw new Error('Export file is empty');
  if(!(await page.request.get(exported.url)).ok())throw new Error('Export download link failed');
  await page.locator('.download-result').waitFor();
  await page.screenshot({path:'verification/storage-export-path.png',fullPage:true});
  if(errors.length)throw new Error(errors.join('\n'));
  const result={status:'passed',settings,beforeCount,liveCount,exported,errors};
  await fs.writeFile('verification/storage-results.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify({status:result.status,beforeCount,liveCount,exported,errors}));
} finally {await browser.close()}
