const {chromium,expect}=require('@playwright/test');
const path=require('path');
const root=path.resolve(__dirname,'../..');
const source=path.join(root,'.test-artifacts','drafts-browser-source.jpg');
require('fs').mkdirSync(path.dirname(source),{recursive:true});
if(!require('fs').existsSync(source))require('child_process').execFileSync(path.join(root,'.venv','Scripts','python.exe'),['-c',"from PIL import Image; import sys; Image.new('RGB',(1200,800),(140,85,40)).save(sys.argv[1])",source]);
const base=process.env.PHOTO_TEST_URL||'http://127.0.0.1:8011';
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const context=await browser.newContext({viewport:{width:1500,height:1000}});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const health=await (await context.request.get(base+'/api/health')).json();
  if(!path.resolve(health.data_dir).startsWith(path.join(root,'.test-artifacts')+path.sep))throw new Error('Refusing to run against a non-test photo library');
  const response=await context.request.post(base+'/api/photos/import',{data:{paths:[source]}});
  const job=await response.json();
  await expect.poll(async()=>(await (await context.request.get(base+'/api/jobs/'+job.id)).json()).status).toBe('completed');
  const photos=await (await context.request.get(base+'/api/photos')).json();const id=photos.photos[0].id;
  // Test-library cleanup uses draft deletion only; no source files are touched.
  const old=await (await context.request.get(base+'/api/watermark/drafts?page_size=100')).json();
  for(const d of old.drafts)await context.request.delete(base+'/api/watermark/drafts/'+d.id);
  await page.goto(base+'/watermark/workshop?photo='+id);
  await expect(page.getByRole('img',{name:'水印实时预览'})).toBeVisible();
  await page.getByRole('button',{name:'沉浸光感',exact:true}).click();
  await page.getByLabel('自定义署名',{exact:true}).check();
  await page.getByPlaceholder('你的摄影署名').fill('E2E Wonder');
  await page.getByLabel('水印作品名称').fill('日落 · 沉浸光感');
  // Navigation must offer save/discard/continue before the first explicit save.
  await page.getByRole('button',{name:'水印图库',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'当前水印尚未保存'})).toBeVisible();
  await page.getByRole('button',{name:'继续编辑',exact:true}).click();
  await page.getByRole('button',{name:'保存到水印图库',exact:true}).click();
  await expect(page).toHaveURL(/draft=/);
  const draftId=new URL(page.url()).searchParams.get('draft');
  await expect.poll(async()=>(await (await context.request.get(base+'/api/watermark/drafts')).json()).total).toBe(1);
  await page.getByPlaceholder('你的摄影署名').fill('Autosaved Wonder');
  await expect.poll(async()=>(await (await context.request.get(base+'/api/watermark/drafts/'+draftId)).json()).settings_json.signature).toBe('Autosaved Wonder');
  await context.close();
  const restoredContext=await browser.newContext({viewport:{width:1500,height:1000}});
  const restored=await restoredContext.newPage();restored.on('pageerror',e=>errors.push(e.message));
  await restored.goto(base+'/watermark/workshop?draft='+draftId);
  await expect(restored.getByPlaceholder('你的摄影署名')).toHaveValue('Autosaved Wonder');
  await expect(restored.getByLabel('水印作品名称')).toHaveValue('日落 · 沉浸光感');
  await restored.getByRole('button',{name:'标记为待导出',exact:true}).click();
  await restored.getByRole('button',{name:'水印图库',exact:true}).click();
  await expect(restored).toHaveURL(/watermark\/gallery/);
  await expect(restored.locator('.draft-card')).toHaveCount(1);
  await restored.locator('.draft-status-tabs button').filter({hasText:'待导出'}).click();
  await expect(restored.locator('.draft-card')).toHaveCount(1);
  await restored.locator('.draft-menu summary').click();
  await restored.getByRole('button',{name:'复制作品',exact:true}).click();
  await restored.locator('.draft-status-tabs button').filter({hasText:'全部'}).click();
  await expect(restored.locator('.draft-card')).toHaveCount(2);
  await restored.getByRole('button',{name:'选择本页',exact:true}).click();
  await restored.getByRole('button',{name:'批量导出',exact:true}).click();
  await expect(restored.getByRole('dialog')).toBeVisible();
  await restored.getByRole('button',{name:'确认导出',exact:true}).click();
  await expect.poll(async()=>{
    const data=await (await restoredContext.request.get(base+'/api/watermark/drafts')).json();
    return data.counts.exported||0;
  }).toBe(2);
  await restored.reload();await expect(restored.locator('.draft-card')).toHaveCount(2);
  await restored.screenshot({path:path.join(root,'.test-artifacts','watermark-gallery.png'),fullPage:true});
  await restored.goto(base+'/watermark/workshop?draft='+draftId);
  await expect(restored.getByPlaceholder('你的摄影署名')).toHaveValue('Autosaved Wonder');
  await restored.getByPlaceholder('你的摄影署名').fill('Changed after export');
  // Leaving immediately must flush the debounce, rather than lose the last keystroke.
  await restored.getByRole('button',{name:'水印图库',exact:true}).click();
  await expect(restored.locator('.draft-card').filter({hasText:'导出后有修改'})).toHaveCount(1);
  await restored.getByLabel('搜索水印作品').fill('Changed after export');
  await expect(restored.locator('.draft-card')).toHaveCount(1);
  await restored.getByLabel('搜索水印作品').fill('');
  await expect(restored.locator('.draft-card')).toHaveCount(2);
  if(errors.length)throw new Error(errors.join('\n'));
  console.log(JSON.stringify({ok:true,draftId,verified:['unsaved navigation guard','explicit first save','debounced autosave','new browser context restore','ready filter','duplicate','batch export','flush on navigation','modified after export','signature search'],screenshot:'.test-artifacts/watermark-gallery.png'}));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
