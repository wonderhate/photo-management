import {chromium} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const output=path.resolve('verification');await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('response',response=>{if(response.status()>=500)errors.push(`${response.status()} ${response.url()}`)});
try{
  await page.goto('http://127.0.0.1:8000',{waitUntil:'networkidle'});
  await page.locator('.photo-card').first().waitFor();
  await page.screenshot({path:path.join(output,'gallery.png'),fullPage:true});
  const count=await page.locator('.photo-card').count();
  if(count<1)throw new Error('No migrated photos rendered');
  await page.locator('.photo-image').first().dblclick();
  await page.locator('.photo-detail').waitFor();
  await page.screenshot({path:path.join(output,'detail.png'),fullPage:true});
  await page.getByRole('button',{name:'制作水印',exact:true}).click();
  await page.locator('.render-stage img').waitFor();
  await page.waitForFunction(()=>!document.querySelector('.render-status')?.textContent.includes('正在'));
  await page.screenshot({path:path.join(output,'watermark-frame.png'),fullPage:true});
  await page.getByRole('button',{name:'沉浸光感',exact:true}).click();
  await page.waitForTimeout(900);
  await page.waitForFunction(()=>!document.querySelector('.render-status')?.textContent.includes('正在'));
  await page.screenshot({path:path.join(output,'watermark-ambient.png'),fullPage:true});
  await page.getByRole('button',{name:'导出当前照片',exact:true}).click();
  await page.locator('.download-result').waitFor();
  await page.locator('nav').getByRole('button',{name:'统计',exact:true}).click();
  await page.locator('.metrics').waitFor();
  await page.screenshot({path:path.join(output,'statistics.png'),fullPage:true});
  await page.locator('.chart-legend button').first().click();
  await page.locator('.filter-chips').waitFor();
  await page.locator('nav').getByRole('button',{name:'摄影报告',exact:true}).click();
  await page.locator('.report-hero').waitFor();
  await page.screenshot({path:path.join(output,'report.png'),fullPage:true});
  await page.locator('.lens-name').first().click();
  await page.locator('.filter-chips').waitFor();
  await page.locator('nav').getByRole('button',{name:'影集',exact:true}).click();
  await page.getByRole('button',{name:'新建影集',exact:true}).click();
  const temporaryName=`浏览器验证 ${Date.now()}`;
  await page.getByLabel('影集名称',{exact:true}).fill(temporaryName);
  await page.getByRole('button',{name:/保存影集/}).click();
  await page.getByRole('heading',{name:temporaryName,exact:true}).waitFor();
  const albums=await (await page.request.get('http://127.0.0.1:8000/api/albums')).json();
  const created=albums.find(a=>a.name===temporaryName);
  if(!created||created.count!==1)throw new Error('Album membership did not persist');
  await page.request.delete(`http://127.0.0.1:8000/api/albums/${created.id}`);
  await page.locator('nav').getByRole('button',{name:/智能影集/}).click();
  await page.getByRole('button',{name:'新建智能影集',exact:true}).click();
  const smartName=`语义浏览器验证 ${Date.now()}`;
  await page.getByLabel('影集名称',{exact:true}).fill(smartName);
  await page.getByLabel('关键词',{exact:true}).fill('城市夜景');
  await page.getByLabel('最多照片',{exact:true}).fill('5');
  await page.getByRole('button',{name:'预览候选照片',exact:true}).click();
  await page.locator('.album-form .photo-card').first().waitFor();
  if(await page.locator('.album-form .photo-card').count()!==5)throw new Error('Expected five real semantic candidates');
  await page.locator('.album-form .select-box').first().click();
  await page.screenshot({path:path.join(output,'smart-album.png'),fullPage:true});
  await page.getByRole('button',{name:/保存影集/}).click();
  await page.getByRole('heading',{name:smartName,exact:true}).waitFor();
  const smartAlbums=await (await page.request.get('http://127.0.0.1:8000/api/albums')).json();
  const smartCreated=smartAlbums.find(a=>a.name===smartName);
  if(smartCreated.count!==4||smartCreated.type!=='smart'||!smartCreated.ai_model)throw new Error('Smart album metadata or selection did not persist');
  await page.request.delete(`http://127.0.0.1:8000/api/albums/${smartCreated.id}`);
  await page.setViewportSize({width:390,height:844});
  await page.locator('nav').getByRole('button',{name:'照片',exact:true}).click();
  await page.waitForTimeout(250);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  if(overflow)errors.push('Mobile page horizontally overflows');
  if(errors.length)throw new Error(errors.join('\n'));
  const report={status:'passed',galleryPhotos:count,checks:['gallery','detail','frame preview','ambient preview','export','stats drilldown','year report','lens drilldown','album persistence','real Chinese semantic preview','manual candidate removal','smart album persistence','mobile layout'],errors};
  await fs.writeFile(path.join(output,'browser-results.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
}finally{await browser.close()}
