import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {join} from 'node:path';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';

test.use({userAgent:'PhotoCollectionRemote/2 Chrome'});
for(const [lang,width] of [['zh',360],['en',430]])test(`phone chooses computer photos and folder ${lang} ${width}`,async({page,request},info)=>{
  const health=await(await request.get('/api/health')).json();
  expect(health.data_dir.replaceAll('\\','/')).toContain('/.test-artifacts/');
  const folder=join(health.data_dir,'Computer Photos # '+lang);
  execFileSync(process.env.PHOTO_TEST_PYTHON||'python',['-c',"from pathlib import Path; from PIL import Image; import sys; p=Path(sys.argv[1]); delta=10 if p.name.endswith('en') else 0; (p/'Trip').mkdir(parents=True,exist_ok=True); (p/'Large Folder').mkdir(exist_ok=True); Image.new('RGB',(641+delta,481),'orange').save(p/'First.jpg'); Image.new('RGB',(642+delta,482),'blue').save(p/'Trip'/'Second.JPG'); (p/'private.txt').write_text('not a photo'); [(p/'Large Folder'/f'Photo-{i:03}.jpg').write_bytes(b'listing only') for i in range(201)]",folder]);
  const first=join(folder,'First.jpg'),second=join(folder,'Trip','Second.JPG');
  const digest=()=>[first,second].map(file=>createHash('sha256').update(readFileSync(file)).digest('hex'));
  const before=digest(),errors=[],imports=[],dialogs=[];
  page.on('pageerror',error=>errors.push(String(error)));
  page.on('request',req=>{if(req.url().includes('/api/dialog/'))dialogs.push(req.url());if(req.url().endsWith('/api/photos/import'))imports.push(req.postDataJSON())});
  await page.setViewportSize({width,height:720});
  await page.addInitScript(lang=>{localStorage.setItem('lang',lang);localStorage.setItem('theme','light')},lang);
  const words=lang==='en'?{import:'Import Photos',photos:'Choose Photos',folder:'Choose Folder',path:'Computer Folder Path',open:'Open Path',next:'Next',previous:'Previous',parent:'Parent Folder',choose:'Use Selected Photos (2)',useFolder:'Use This Folder',cancel:'Cancel',start:'Start Import',recursive:'Include subfolders'}:{import:'导入照片',photos:'选择照片',folder:'选择文件夹',path:'电脑文件夹路径',open:'打开路径',next:'下一页',previous:'上一页',parent:'上一级',choose:'使用已选照片（2）',useFolder:'选择这个文件夹',cancel:'取消',start:'开始导入',recursive:'包含子文件夹'};
  async function begin(kind){await page.locator('.topbar-actions').getByRole('button',{name:words.import,exact:true}).click();await page.locator('.import-choices').getByRole('button',{name:kind}).click();await expect(page.locator('.computer-picker')).toBeVisible();await expect(page.getByRole('button',{name:words.open,exact:true})).toBeEnabled()}
  async function openFolder(path){await page.getByLabel(words.path,{exact:true}).fill(path);await page.getByRole('button',{name:words.open,exact:true}).click();await expect(page.getByRole('button',{name:words.open,exact:true})).toBeEnabled()}
  await page.goto('/?page=photos');await begin(words.photos);
  await expect(page.locator('.computer-import .modal>header button')).toBeFocused();
  expect(await page.locator('.scrim.computer-import').evaluate(el=>getComputedStyle(el).backgroundColor)).toContain('247, 245, 240');
  await openFolder(folder);
  await expect(page.locator('.computer-file-list')).not.toContainText('private.txt');
  await page.getByRole('checkbox',{name:'First.jpg',exact:true}).check();
  await page.locator('.computer-file-list').getByRole('button',{name:'Trip',exact:true}).click();
  await page.getByRole('checkbox',{name:'Second.JPG',exact:true}).check();
  await page.getByRole('button',{name:words.parent,exact:true}).click();
  await page.locator('.computer-file-list').getByRole('button',{name:'Large Folder',exact:true}).click();
  await page.getByRole('button',{name:words.next,exact:true}).click();
  await expect(page.locator('.computer-picker-pagination')).toContainText('2 / 2');
  await expect(page.getByRole('checkbox',{name:'Photo-200.jpg',exact:true})).toBeVisible();
  await page.getByRole('button',{name:words.previous,exact:true}).click();
  await expect(page.locator('.computer-picker-pagination')).toContainText('1 / 2');
  await page.getByRole('button',{name:words.parent,exact:true}).click();
  await expect(page.locator('label.computer-file-row').first()).toHaveCSS('flex-direction','row');
  await expect(page.getByRole('button',{name:words.choose,exact:true})).toBeInViewport({ratio:1});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  if(lang==='en')expect(await page.getByRole('dialog').innerText()).not.toMatch(/[\u3400-\u9fff]/u);
  await page.screenshot({path:info.outputPath('computer-picker.png')});
  await page.getByRole('button',{name:words.choose,exact:true}).click();
  await expect(page.locator('.import-content textarea')).toHaveValue(first+'\n'+second);
  await expect(page.getByRole('button',{name:words.start,exact:true})).toBeFocused();
  await page.getByRole('button',{name:words.start,exact:true}).click();
  expect(imports).toEqual([{paths:[first,second],recursive:true}]);
  await expect.poll(async()=>{const photos=await(await request.get('/api/photos')).json();return photos.photos.filter(p=>[first,second].includes(p.file_path)).length}).toBe(2);
  expect(digest()).toEqual(before);
  await begin(words.folder);await openFolder(join(folder,'Trip'));
  await expect(page.locator('.computer-file-list')).not.toContainText('Second.JPG');
  await page.getByRole('button',{name:words.useFolder,exact:true}).click();
  await expect(page.locator('.import-content textarea')).toHaveValue(join(folder,'Trip'));
  await page.getByRole('checkbox',{name:words.recursive,exact:true}).uncheck();
  await page.locator('.import-choices').getByRole('button',{name:words.photos}).click();
  await expect(page.getByRole('button',{name:words.open,exact:true})).toBeEnabled();
  await openFolder(join(folder,'Missing Folder'));
  await expect(page.getByRole('alert')).toContainText(lang==='en'?'Computer folder does not exist':'电脑上的文件夹不存在');
  await page.getByRole('button',{name:words.cancel,exact:true}).click();
  await expect(page.locator('.import-content textarea')).toHaveValue(join(folder,'Trip'));
  await page.getByRole('button',{name:words.cancel,exact:true}).click();
  expect(imports).toHaveLength(1);expect(dialogs).toEqual([]);expect(errors).toEqual([]);
});
