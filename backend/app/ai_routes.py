from fastapi import APIRouter, HTTPException, Query
from fastapi.responses import FileResponse
from sqlalchemy import select,func
from .models import Session, AIResult
from .ai_schemas import Profile,Scope,Authorize,Create,HandwritingLayout,AnnotationRepair,PlaceReview,ProfileExport
from .services import ai_studio as studio
from .services.ai_styles import STYLES

router=APIRouter(prefix='/api/ai',tags=['domestic-ai'])


@router.get('/profiles')
def profiles():return studio.profiles()


@router.post('/profiles',status_code=201)
def add_profile(payload:Profile):return studio.save_profile(None,payload)


@router.put('/profiles/{id}')
def update_profile(id:str,payload:Profile):return studio.save_profile(id,payload)


@router.delete('/profiles/{id}')
def delete_profile(id:str):studio.delete_profile(id);return {'ok':True}


@router.post('/profile-transfer/export')
def export_profiles(payload:ProfileExport):
    from fastapi.responses import JSONResponse
    return JSONResponse(studio.export_profiles(payload.profile_ids),headers={'Cache-Control':'no-store'})


@router.get('/styles')
def styles():return STYLES


@router.post('/annotation-scope')
def scope(payload:Scope):return studio.snapshot_scope(payload)


@router.post('/annotate',status_code=202)
def annotate(payload:Authorize):return studio.submit_annotation(payload)


@router.post('/create',status_code=202)
def create(payload:Create):return studio.submit_creation(payload)


@router.get('/results')
def results(photo_id:str|None=None,kind:str|None=None,page:int=Query(1,ge=1),page_size:int=Query(24,ge=1,le=100)):
    with Session() as s:
        q=select(AIResult)
        if photo_id:q=q.where(AIResult.photo_id==photo_id)
        if kind:q=q.where(AIResult.kind==kind)
        total=s.scalar(select(func.count()).select_from(q.subquery()))
        rows=s.scalars(q.order_by(AIResult.created_at.desc(),AIResult.id).offset((page-1)*page_size).limit(page_size))
        return dict(items=[studio.result_view(r) for r in rows],total=total)


@router.get('/results/{id}')
def result(id:str):
    with Session() as s:
        row=s.get(AIResult,id)
        if row is None:raise HTTPException(404,'AI result not found.')
        return studio.result_view(row)


@router.get('/results/{id}/{kind}')
def image(id:str,kind:str):
    if kind not in ('image','preview'):raise HTTPException(404)
    with Session() as s:
        row=s.get(AIResult,id)
        if row is None or row.kind=='annotation':raise HTTPException(404)
        return FileResponse(studio.result_path(row,kind=='preview'),headers={'Cache-Control':'no-cache'})


@router.post('/results/{id}/repair')
def repair(id:str,payload:AnnotationRepair):return studio.apply_result(id,payload.revision,payload.result)


@router.post('/results/{id}/place-review')
def place_review(id:str,payload:PlaceReview):return studio.review_place(id,payload)


@router.post('/results/{id}/export')
def export(id:str):return studio.export_result(id)


@router.post('/results/{id}/handwriting-export')
def handwriting(id:str,payload:HandwritingLayout):return studio.export_result(id,payload)


@router.delete('/results/{id}')
def delete(id:str):
    with studio.lock,Session() as s:
        row=s.get(AIResult,id)
        if row:s.delete(row);s.commit()
        # Keep generated bytes and all originals. Explicit lifecycle recycling
        # remains responsible for files that are no longer referenced.
        return {'ok':True}
