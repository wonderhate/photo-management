// Generate public tutorial images using exactly the in-app demo renderers.
// This script reads no library and writes only the three declared demo assets.
import {createServer} from 'vite';
import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const server=await createServer({root,mode:'browser',server:{host:'127.0.0.1',port:5193,strictPort:true}});
let browser;
try{
 await server.listen();browser=await chromium.launch({channel:process.env.CI?undefined:'chrome',headless:true});
 const page=await browser.newPage();
 await page.route('**/*',route=>new URL(route.request().url()).origin==='http://127.0.0.1:5193'?route.continue():route.abort());
 await page.goto('http://127.0.0.1:5193/?local=1&demo=1');
 const results=await page.evaluate(async()=>{
  const {createDemoImage,demoRecipe,demoFrame}=await import('/src/browser/demo-image.ts');
  const {EditSession}=await import('/src/browser/edit-session.ts');
  const {renderFrameV2}=await import('/src/browser/frame-v2-render.ts');
  const session=new EditSession();
  try{
   const source=await createDemoImage();await session.open(source);
   const original=await session.export(demoRecipe(0,0),0,'png',100);
   const adjusted=await session.export(demoRecipe(.5,25),0,'png',100);
   const framed=await renderFrameV2(adjusted.blob,demoFrame('paper'),undefined,0,'png',100);
   const result=[];
   for(const [name,blob] of [['original',original.blob],['adjusted',adjusted.blob],['framed',framed]]){
    const bitmap=await createImageBitmap(blob);const dimensions={width:bitmap.width,height:bitmap.height};bitmap.close();
    result.push({name,...dimensions,bytes:[...new Uint8Array(await blob.arrayBuffer())]});
   }return result;
  }finally{session.dispose();}
 });
 const directories=[new URL('../public/demo/',import.meta.url),new URL('../../../frontend/public/demo/',import.meta.url)];
 for(const directory of directories){
  await mkdir(directory,{recursive:true});
  for(const image of results)await writeFile(new URL('lumina-'+image.name+'.png',directory),Buffer.from(image.bytes));
  await writeFile(new URL('source.json',directory),JSON.stringify({source:'Original procedural illustration generated by Lumina; not a photograph or a user photo.',license:'MIT',generator:'web/frontend/scripts/generate-first-use-demo.mjs',imageSource:'web/frontend/src/browser/demo-image.ts',adjustments:{exposure:.5,saturation:25,frame:'paper'},renderer:'EditSession.export + renderFrameV2',files:results.map(({name,width,height})=>({name:'lumina-'+name+'.png',width,height}))},null,2)+'\n');
 }
 console.log(JSON.stringify(results.map(({name,width,height,bytes})=>({name,width,height,bytes:bytes.length}))));
}finally{await browser?.close();await server.close();}
